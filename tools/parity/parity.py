"""
The parity harness: prove mobile matches web, instead of asserting it.

    python tools/parity/parity.py                 # owner pass
    python tools/parity/parity.py --role artist
    python tools/parity/parity.py --screens team,clients
    python tools/parity/parity.py --keep-servers   # leave vite/expo up

Output lands in `tools/parity/out/<date>/` with an `index.html` contact
sheet. Nothing is fixed here — the output is a punch list.

─── WHAT IT DOES ───────────────────────────────────────────────────────

1. Boots apps/web (vite) and the apps/mobile web harness against the SAME
   dev database, and signs BOTH in as the SAME account.
2. Per screen: web at 390x844, web at 1440x900, mobile at 390x844.
   Composites web|mobile side by side, and diffs the two mobile-width
   shots where geometry is comparable.
3. Reads computed values off named landmarks on both sides and tabulates
   property | web | mobile | match.
4. Classifies every difference as EXPECTED (named in
   expected-divergences.md) or DRIFT. Drift is the punch list.

─── WHAT IT IS NOT VALID FOR ───────────────────────────────────────────

Layout, type, colour and spacing: valid. MOTION, GESTURES and true native
rendering: NOT VALID, and no output here should be read as covering them.
Reanimated does not advance inside app subtrees under this harness and
gesture-handler is inert to synthetic input — both are recorded in
CLAUDE.md. Those still need the owner's device gate.

─── THE PREVIEW ROUTE ──────────────────────────────────────────────────

The mobile app cannot log in under expo web (secure-store plus CORS), so
a signed-in screen is only reachable by injecting a session. Every
session so far has hand-written a throwaway `preview-XX.tsx`, used it,
and deleted it — which is why this harness exists.

It is still written and removed per run rather than living in
`apps/mobile/src/app` permanently: this is a tool, and a route that ships
in the production bundle to serve it is product code. `_cleanup_stale()`
removes one left behind by a crashed run before starting.
"""

